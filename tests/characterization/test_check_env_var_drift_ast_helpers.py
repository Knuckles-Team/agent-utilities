# _compose_env_keys / _compose_subst_reads
# ---------------------------------------------------------------------------
def test_compose_env_keys_block_terminated_by_dedent(tmp_path):
    pkg = tmp_path / "pkgcompose"
    pkg.mkdir()
    (pkg / "docker-compose.yml").write_text(
        "services:\n"
        "  demo:\n"
        "    environment:\n"
        "      - FOO=bar\n"
        "      - BAZ=qux\n"
        "    ports:\n"
        '      - "8080:8080"\n',
        encoding="utf-8",
    )
    keys = drift._compose_env_keys(pkg)
    assert keys == {"docker-compose.yml": {"FOO", "BAZ"}}


def test_compose_subst_reads_image_and_command(tmp_path):
    pkg = tmp_path / "pkgsubst"
    pkg.mkdir()
    (pkg / "docker-compose.yml").write_text(
        "services:\n"
        "  demo:\n"
        "    image: ${DEMO_IMAGE:?required}\n"
        "    command:\n"
        '      - "${DEMO_ARG}"\n',
        encoding="utf-8",
    )
    found = drift._compose_subst_reads(pkg)
    assert found == {"DEMO_IMAGE", "DEMO_ARG"}


def test_compose_third_party_file_skipped(tmp_path, monkeypatch):
    pkg = tmp_path / "pkgthirdparty"
    pkg.mkdir()
    fname = "postgres-compose.yml"
    monkeypatch.setattr(drift, "_THIRD_PARTY_COMPOSE_FILES", frozenset({fname}))
    (pkg / fname).write_text(
        "services:\n  db:\n    environment:\n      - POSTGRES_PASSWORD=x\n",
        encoding="utf-8",
    )
    assert drift._compose_env_keys(pkg) == {}
    assert drift._compose_subst_reads(pkg) == set()


# ---------------------------------------------------------------------------
# analyze() -- overall return shape (light integration smoke)
# ---------------------------------------------------------------------------
def test_analyze_return_shape(tmp_path):
    root = _make_pkg(
        tmp_path,
        env_example="",
        mcp_config={"mcpServers": {}},
        code="",
    )
    report = drift.analyze(root)
    assert set(report.keys()) == {"package", "code_read_count", "findings", "drift"}
    assert report["drift"] == len(report["findings"])
    assert report["package"] == "demo-agent"


