from __future__ import annotations

import ast
import json
from pathlib import Path

import pytest

from agent_utilities.mcp import check_env_var_drift as drift


def _tree(src: str) -> ast.AST:
    return ast.parse(src)


# ---------------------------------------------------------------------------
# _env_names_from_tree
# ---------------------------------------------------------------------------
def test_direct_setting_call_found():
    found = drift._env_names_from_tree(_tree('setting("FOO_BAR", "")'))
    assert found == {"FOO_BAR"}


def test_os_getenv_found():
    found = drift._env_names_from_tree(_tree('import os\nos.getenv("BAZ_QUX")'))
    assert found == {"BAZ_QUX"}


def test_environ_get_and_subscript_found():
    found = drift._env_names_from_tree(
        _tree('import os\nos.environ.get("A_VAR")\nos.environ["B_VAR"]')
    )
    assert found == {"A_VAR", "B_VAR"}


def test_environ_write_not_counted_as_read():
    found = drift._env_names_from_tree(_tree('import os\nos.environ["WRITTEN"] = "x"'))
    assert found == set()


def test_same_module_alias_indirection_resolved():
    """`_LOG_LEVEL = "X_LOG_LEVEL"` then `os.getenv(_LOG_LEVEL)` -- the read is
    counted even though the literal never appears next to the reader call."""
    src = '_LOG_LEVEL = "X_LOG_LEVEL"\nimport os\nos.getenv(_LOG_LEVEL)\n'
    assert drift._env_names_from_tree(_tree(src)) == {"X_LOG_LEVEL"}


def test_unaliased_name_arg_not_counted():
    src = "value = compute()\nos.getenv(value)\n"
    assert drift._env_names_from_tree(_tree(src)) == set()


def test_field_alias_found():
    src = 'from pydantic import Field\nx: str = Field(alias="PYD_VAR")\n'
    assert drift._env_names_from_tree(_tree(src)) == {"PYD_VAR"}


def test_enable_flag_assignment_found():
    src = 'self.enable_flag = "FEATURE_ENABLED"\n'
    assert drift._env_names_from_tree(_tree(src)) == {"FEATURE_ENABLED"}


def test_string_literal_lookalike_ignored():
    src = "doc = \"setting('NOT_A_READ')\"\n"
    assert drift._env_names_from_tree(_tree(src)) == set()


