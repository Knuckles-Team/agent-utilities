def test_mcp_config_env_blocks_dedupes_identical_blocks(tmp_path):
    pkg = tmp_path / "pkgdedupe"
    pkg.mkdir()
    cfg = {"mcpServers": {"a": {"env": {"X": "1"}}, "b": {"env": {"X": "1"}}}}
    (pkg / "mcp_config.json").write_text(json.dumps(cfg), encoding="utf-8")
    blocks = drift._mcp_config_env_blocks(pkg)
    # Two servers with an IDENTICAL env dict de-dup to one entry (same path + frozenset).
    assert len(blocks) == 1


def test_mcp_config_env_blocks_skips_data_scaffold_template(tmp_path):
    pkg = tmp_path / "pkgscaffold"
    (pkg / "agent_utilities" / "data").mkdir(parents=True)
    cfg = {"mcpServers": {"example-mcp": {"env": {"API_KEY": "x"}}}}
    (pkg / "agent_utilities" / "data" / "mcp_config.json").write_text(
        json.dumps(cfg), encoding="utf-8"
    )
    assert drift._mcp_config_env_blocks(pkg) == []


