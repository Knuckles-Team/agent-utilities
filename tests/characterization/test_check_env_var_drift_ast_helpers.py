# _module_level_string_tuples
# ---------------------------------------------------------------------------
def test_module_level_string_tuple_captured():
    tree = _tree('SUFFIXES = ("A", "B", "C")\n')
    assert drift._module_level_string_tuples(tree) == {"SUFFIXES": ("A", "B", "C")}


def test_module_level_tuple_with_non_literal_element_excluded():
    tree = _tree('SUFFIXES = ("A", compute(), "C")\n')
    assert drift._module_level_string_tuples(tree) == {}


def test_module_level_list_also_captured():
    tree = _tree('SUFFIXES = ["A", "B"]\n')
    assert drift._module_level_string_tuples(tree) == {"SUFFIXES": ("A", "B")}


def test_non_tuple_assignment_ignored():
    tree = _tree('NAME = "just-a-string"\n')
    assert drift._module_level_string_tuples(tree) == {}


# ---------------------------------------------------------------------------
# _scan_dynamic_families / _scan_dynamic_family_reads (direct + via analyze())
# ---------------------------------------------------------------------------
def _make_pkg(tmp_path: Path, *, env_example: str, mcp_config: dict, code: str) -> Path:
    root = tmp_path / "demo-agent"
    (root / "demo_agent").mkdir(parents=True)
    (root / ".env.example").write_text(env_example, encoding="utf-8")
    (root / "mcp_config.json").write_text(json.dumps(mcp_config), encoding="utf-8")
    (root / "demo_agent" / "auth.py").write_text(code, encoding="utf-8")
    return root


def test_scan_dynamic_families_direct(tmp_path):
    pkg = tmp_path / "pkgdirect"
    pkg.mkdir()
    (pkg / "mod.py").write_text(
        "def resolve_profile(service, other=None):\n"
        "    pass\n"
        'resolve_profile.dynamic_env_prefix_arg = "service"\n'
        'resolve_profile.dynamic_env_suffixes = ("TLS_PROFILE", "TLS_PROFILE_REF")\n',
        encoding="utf-8",
    )
    families = drift._scan_dynamic_families(pkg)
    assert "resolve_profile" in families
    prefix_arg, position, suffixes = families["resolve_profile"]
    assert prefix_arg == "service"
    assert position == 0
    assert suffixes == ("TLS_PROFILE", "TLS_PROFILE_REF")


def test_scan_dynamic_family_reads_direct(tmp_path):
    pkg = tmp_path / "pkgreads"
    pkg.mkdir()
    (pkg / "mod.py").write_text('resolve_profile("mealie")\n', encoding="utf-8")
    families = {"resolve_profile": ("service", 0, ("TLS_PROFILE", "TLS_PROFILE_REF"))}
    found = drift._scan_dynamic_family_reads(pkg, families)
    assert found == {"MEALIE_TLS_PROFILE", "MEALIE_TLS_PROFILE_REF"}


def test_scan_dynamic_family_reads_empty_families_short_circuits(tmp_path):
    pkg = tmp_path / "pkgempty"
    pkg.mkdir()
    (pkg / "mod.py").write_text('resolve_profile("mealie")\n', encoding="utf-8")
    assert drift._scan_dynamic_family_reads(pkg, {}) == set()


