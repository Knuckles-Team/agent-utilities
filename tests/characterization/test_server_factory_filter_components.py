# ---------------------------------------------------------------------------
# 5. Env-based tag filters: enabled tag must intersect; components without
#    tags are then excluded once an enabled-tag filter is active.
# ---------------------------------------------------------------------------
def test_env_enabled_tags_require_intersection(clean_env):
    clean_env.setenv("MCP_ENABLED_TAGS", "kg")
    transform = _build_transform()
    comps = [
        _Component(name="a", tags={"kg"}),
        _Component(name="b", tags={"other"}),
        _Component(name="c", tags=None),
    ]
    out = transform._filter_components(comps)
    # "c" has no tags at all -> excluded once an enabled-tag filter is set.
    assert _names(out) == ["a"]


def test_env_disabled_tags_exclude_on_intersection(clean_env):
    clean_env.setenv("MCP_DISABLED_TAGS", "danger")
    transform = _build_transform()
    comps = [
        _Component(name="a", tags={"danger"}),
        _Component(name="b", tags={"safe"}),
        _Component(name="c", tags=None),
    ]
    out = transform._filter_components(comps)
    # disabled-tags-only: components with no tags are NOT excluded (only the
    # enabled-tags branch penalizes an untagged component).
    assert _names(out) == ["b", "c"]


# ---------------------------------------------------------------------------
# 6. A component with neither `name` nor `uri` is EXCLUDED (BUG-CX-022, fixed
#    by lane WD2-BUG-SEC). This pin previously recorded the OPPOSITE -- that
#    such a component bypassed BOTH name and tag filtering -- which was the
#    security defect itself, not behaviour worth preserving. See
#    tests/unit/mcp/test_server_factory_fail_closed.py for the full fail-closed
#    regression set.
# ---------------------------------------------------------------------------
def test_unnamed_component_is_excluded_by_filtering(clean_env):
    clean_env.setenv("MCP_ENABLED_TOOLS", "only-this-one")
    clean_env.setenv("MCP_ENABLED_TAGS", "some-tag")
    transform = _build_transform()
    anon = _Component(name=None, uri=None, tags={"unrelated"})
    named = _Component(name="only-this-one", tags={"some-tag"})
    excluded = _Component(name="excluded", tags={"some-tag"})
    out = transform._filter_components([anon, named, excluded])
    assert anon not in out
    assert named in out
    assert excluded not in out


