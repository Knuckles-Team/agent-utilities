from __future__ import annotations

from types import SimpleNamespace

import pytest

from agent_utilities.mcp.server_factory import create_mcp_server


class _Component:
    """Minimal stand-in for a FastMCP Tool/Resource/Prompt as `_filter_components` sees it."""

    def __init__(self, name=None, uri=None, tags=None):
        self.name = name
        self.uri = uri
        self.tags = tags

    def __repr__(self):
        return f"_Component(name={self.name!r}, uri={self.uri!r}, tags={self.tags!r})"


def _build_transform(command_args=None):
    """Build a real server and return its live DynamicVisibilityTransform."""
    _args, mcp, _mw = create_mcp_server(
        name="cx-au-05-test-server", command_args=command_args or []
    )
    transforms = [
        t for t in mcp.transforms if type(t).__name__ == "DynamicVisibilityTransform"
    ]
    assert len(transforms) == 1, "expected exactly one DynamicVisibilityTransform"
    return transforms[0]


def _names(components):
    return sorted(c.name for c in components)


@pytest.fixture
def clean_env(monkeypatch):
    """No env-based filters, no request context, no CLI overrides."""
    for key in (
        "MCP_ENABLED_TAGS",
        "MCP_DISABLED_TAGS",
        "MCP_ENABLED_TOOLS",
        "MCP_DISABLED_TOOLS",
    ):
        monkeypatch.delenv(key, raising=False)
    monkeypatch.setattr(
        "agent_utilities.mcp.server_factory._optional_http_request", lambda: None
    )
    return monkeypatch


# ---------------------------------------------------------------------------
# 1. No filters configured at all -> everything passes through unchanged.
# ---------------------------------------------------------------------------
def test_no_filters_returns_all_components(clean_env):
    transform = _build_transform()
    comps = [_Component(name="a"), _Component(name="b"), _Component(name="c")]
    out = transform._filter_components(comps)
    assert _names(out) == ["a", "b", "c"]


