# 8. Query-parameter based filtering (HTTP/SSE transport only).
# ---------------------------------------------------------------------------
class _FakeQueryParams:
    def __init__(self, data):
        self._data = data

    def getlist(self, key):
        val = self._data.get(key)
        if val is None:
            return []
        return val if isinstance(val, list) else [val]

    def get(self, key):
        val = self._data.get(key)
        if isinstance(val, list):
            return val[0] if val else None
        return val


class _FakeHeaders:
    def __init__(self, data):
        self._data = data or {}

    def getlist(self, key):
        val = self._data.get(key)
        if val is None:
            return []
        return val if isinstance(val, list) else [val]

    def get(self, key):
        val = self._data.get(key)
        if isinstance(val, list):
            return val[0] if val else None
        return val


def _fake_request(query=None, headers=None):
    return SimpleNamespace(
        query_params=_FakeQueryParams(query or {}), headers=_FakeHeaders(headers or {})
    )


def test_query_param_tools_narrows_enabled_list(clean_env):
    clean_env.setenv("MCP_ENABLED_TOOLS", "a,b,c")
    transform = _build_transform()
    req = _fake_request(query={"tools": "b,c"})
    clean_env.setattr(
        "agent_utilities.mcp.server_factory._optional_http_request", lambda: req
    )
    comps = [_Component(name="a"), _Component(name="b"), _Component(name="c")]
    out = transform._filter_components(comps)
    assert _names(out) == ["b", "c"]


