def test_stdio_transport_is_a_noop():
    args = _net_args(transport="stdio")
    _validate_network_exposure(args)  # must not raise


def test_loopback_bind_is_a_noop():
    args = _net_args(host="127.0.0.1", auth_type="none")
    _validate_network_exposure(args)  # must not raise


def test_unauthenticated_network_listener_rejected():
    args = _net_args(auth_type="none")
    with pytest.raises(SystemExit):
        _validate_network_exposure(args)


def test_mismatched_cert_and_key_rejected(tmp_path):
    cert = tmp_path / "c.pem"
    cert.write_text("x")
    args = _net_args(auth_type="jwt", tls_certfile=str(cert), tls_keyfile="")
    with pytest.raises(SystemExit):
        _validate_network_exposure(args)


