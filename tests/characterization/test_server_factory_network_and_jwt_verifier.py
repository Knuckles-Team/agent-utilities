def test_stdio_transport_returns_empty_dict():
    args = _net_args(transport="stdio")
    assert mcp_network_run_kwargs(args) == {}


def test_non_loopback_without_allowed_hosts_raises():
    args = _net_args(allowed_hosts="")
    with pytest.raises(RuntimeError):
        mcp_network_run_kwargs(args)


def test_loopback_without_allowed_hosts_synthesizes_defaults():
    args = _net_args(host="127.0.0.1", allowed_hosts="", port=9123)
    result = mcp_network_run_kwargs(args)
    assert "middleware" in result and "uvicorn_config" in result


def test_valid_network_config_builds_middleware_and_uvicorn_config():
    args = _net_args(allowed_hosts="svc.example.com", allowed_origins="")
    result = mcp_network_run_kwargs(args)
    assert len(result["middleware"]) == 3
    assert result["uvicorn_config"]["proxy_headers"] is False
    assert "ssl_certfile" not in result["uvicorn_config"]


def test_tls_terminated_prepends_trusted_proxy_middleware():
    args = _net_args(
        allowed_hosts="svc.example.com",
        tls_terminated=True,
        trusted_proxy_cidrs="10.0.0.0/8",
    )
    result = mcp_network_run_kwargs(args)
    assert len(result["middleware"]) == 4


def test_tls_files_set_ssl_config():
    args = _net_args(
        allowed_hosts="svc.example.com",
        tls_certfile="c.pem",
        tls_keyfile="k.pem",
    )
    result = mcp_network_run_kwargs(args)
    assert result["uvicorn_config"]["ssl_certfile"] == "c.pem"
    assert result["uvicorn_config"]["ssl_keyfile"] == "k.pem"


def test_invalid_connection_bounds_raises(monkeypatch):
    monkeypatch.setenv("MCP_MAX_CONNECTIONS", "0")
    args = _net_args(allowed_hosts="svc.example.com")
    with pytest.raises(RuntimeError):
        mcp_network_run_kwargs(args)


