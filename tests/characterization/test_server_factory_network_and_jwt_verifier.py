def _run(coro):
    return asyncio.run(coro)


def _net_args(**overrides):
    parser = create_mcp_parser()
    args, _ = parser.parse_known_args([])
    args.transport = "streamable-http"
    args.host = "0.0.0.0"
    for key, value in overrides.items():
        setattr(args, key, value)
    return args


